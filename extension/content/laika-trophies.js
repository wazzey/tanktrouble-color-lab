// every wearable reward of a trophy: its item, plus the earlier drawn ("classic") version where there is one
export const rewardsOf = (t) =>
  (t.noItem ? [] : [[t.key, t.slot, t.item]])
    .concat(t.alt ? [[t.alt, t.altSlot, t.altItem]] : [])
    .concat(t.extra || []);
export const BONE_KEYS = new Set(["dimitrium", "galaxy", "supernova", "dimitri-bone"]); // made from the gold bone
export const trophyById = (id) => TROPHIES.find((t) => t.id === String(id));
export const trophyByKey = (k) =>
  TROPHIES.find((t) => t.key === k || t.alt === k || (t.extra || []).some((r) => r[0] === k));
export const isTrophyVal = (v) => typeof v === "string" && v.startsWith("ttcl:");
