// Accepts "#abc", "#aabbcc", "aabbcc", "0xaabbcc" -> "0xaabbcc" (or null if invalid/empty)
export function normHex(v) {
  if (v == null) {
    return null;
  }
  let s = String(v)
    .trim()
    .toLowerCase()
    .replace(/^#|^0x/, "");
  if (/^[0-9a-f]{3}$/.test(s)) {
    s = s
      .split("")
      .map((c) => c + c)
      .join("");
  }
  return /^[0-9a-f]{6}$/.test(s) ? "0x" + s : null;
}
