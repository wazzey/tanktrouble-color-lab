// One sheet a theme holds its letters, digits, symbol and particles; a year's sign is put together from it.
// Glyph rows are [x, y, w, h] on the sheet then [left, top, width, height, first solid row] on the tank; stars are
// [x, y, radius, opacity] of the game's own stars.
export function drawTtocSign(g, theme, year, sheet) {
  const layout = TTOC_SHEETS[theme],
    yearData = TTOC_YEARS[year],
    boxes = yearData.boxes;
  yearData.stars.forEach(([cx, cy, radius, opacity], i) => {
    const [px, py, pw, ph, fullW, fullH] = layout.parts[i % layout.parts.length],
      scale = (2 * radius * (opacity > 0.42 ? 1 : 0.55)) / Math.max(fullW, fullH),
      width = fullW * scale,
      height = fullH * scale;
    g.globalAlpha = opacity; // (as see-through as the game's own star there)
    g.drawImage(sheet, px, py, pw, ph, Math.round(cx - width / 2), Math.round(cy - height / 2), width, height);
  });
  g.globalAlpha = 1;
  const placed = [];
  const placeGlyph = (index, box) => {
    const [gx, gy, gw, gh, left, top, width, height, firstRow] = layout.glyphs[index];
    placed.push([gx, gy, gw, gh, box[0] + left, box[2] + top, width, height, box[2] + top + firstRow]);
  };
  for (let i = 0; i < 4; i++) {
    placeGlyph(i, boxes[i]);
  }
  {
    const [sx, sy, sw, sh, fullW, fullH] = layout.symbol,
      box = boxes[4],
      scale = Math.min(1, ((box[3] - box[2]) * 1.25) / fullH, ((box[1] - box[0]) * 1.25) / fullW),
      width = fullW * scale,
      height = fullH * scale,
      top = (box[2] + box[3]) / 2 - height / 2;
    placed.push([sx, sy, sw, sh, (box[0] + box[1]) / 2 - width / 2, top, width, height, top]);
  }
  String(year)
    .split("")
    .forEach((digit, j) => {
      placeGlyph(4 + Number(digit), boxes[5 + j]);
    });
  const shift = Math.max(0, 2 - Math.min(...placed.map((layer) => layer[8]))); // (snow, flames or drips above the picture's top edge)
  for (const [gx, gy, gw, gh, left, top, width, height] of placed) {
    g.drawImage(sheet, gx, gy, gw, gh, Math.round(left), Math.round(top + shift), width, height);
  }
}
// a whole sign on its own, for the box's picture
export async function readTtocSign(key) {
  const [, theme, year] = key.split("-"),
    sheet = await loadImg(TTOC_SHEETS[theme].sheet);
  if (!sheet) {
    return null;
  }
  const c = document.createElement("canvas");
  c.width = 640;
  c.height = 384;
  drawTtocSign(c.getContext("2d"), theme, Number(year), sheet);
  return c;
}
for (const t of TTOC_THEMES) {
  const [red, green, blue] = t.accent;
  EXT_BOXPIC[t.id] = {
    ramp: [
      [0, [red * 0.1, green * 0.1, blue * 0.1]],
      [0.35, [red * 0.42, green * 0.42, blue * 0.42]],
      [0.65, [red, green, blue]],
      [0.88, [red + (255 - red) * 0.6, green + (255 - green) * 0.6, blue + (255 - blue) * 0.6]],
      [1, [255, 255, 255]],
    ],
    overlay() {},
  };
  for (let year = 18; year <= 26; year++) {
    const key = "tt-" + t.theme + "-" + year;
    GX_ACC[key] = { slot: "barrel", name: "TTOC " + year + " Sign (" + t.name + ")", box: t.id };
    EXT_ITEM[key] = {
      uses: [TTOC_SHEETS[t.theme].sheet],
      draw(g, K, P, A) {
        const sheet = A[TTOC_SHEETS[t.theme].sheet];
        if (sheet) {
          drawTtocSign(g, t.theme, year, sheet);
        }
      },
    };
  }
}
